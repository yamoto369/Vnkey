#!/usr/bin/env python3
"""Builds Engine/EnglishFormsData.h: real English word forms our frequency list (en_50k, subtitles) is missing,
such as "resets" and "quests" (D60). Source: the SCOWL en_US Hunspell dictionary, every form expanded by its affix
rules (plurals, past tense, -ing, irregular forms). The engine counts them as English rarer than every listed word.

usage: build_forms.py DIR   (DIR has en_US.dic and en_US.aff from hunspell-en_US-<date>.zip, github.com/en-wl/wordlist
                             releases; needs Hunspell's unmunch: brew install hunspell)
  FORMS=listed (default): only forms of a dictionary entry whose base word is in our list; FORMS=all: every form.
SCOWL/ESDB copyright Kevin Atkinson, permissive license (see ACKNOWLEDGEMENTS.md)."""
import os, re, subprocess, sys, tempfile
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'Engine', 'EnglishFormsData.h')
src = sys.argv[1]
mode = os.environ.get('FORMS', 'listed')

h = open(os.path.join(HERE, '..', '..', 'Engine', 'AutoSwitchData.h')).read()
block = re.search(r'kAutoSwitchEnWords\[\] =\n(.*?);\n', h, re.S).group(1)
listed = set(w for w in ''.join(re.findall(r'"(.*?)"', block)).split('\\0') if w)

# Expand entry by entry: a separator entry after each line keeps every form with its dictionary entry.
entries = [l for l in open(os.path.join(src, 'en_US.dic'), encoding='utf-8', errors='replace').read().split('\n')[1:] if l.strip()]
with tempfile.TemporaryDirectory() as tmp:
    dic = os.path.join(tmp, 'sep.dic')
    with open(dic, 'w', encoding='utf-8') as f:
        f.write(f'{2 * len(entries)}\n')
        for i, e in enumerate(entries): f.write(f'{e}\nqqsep{i}\n')
    out = subprocess.run(['unmunch', dic, os.path.join(src, 'en_US.aff')], capture_output=True).stdout.decode('utf-8', 'replace')
groups, cur = [], []
for w in out.split('\n'):
    if w.startswith('qqsep'): groups.append(cur); cur = []
    elif w: cur.append(w)

forms = set()
for g in groups:
    if not g or (mode == 'listed' and g[0] not in listed): continue
    forms.update(w for w in g if re.fullmatch('[a-z]{2,}', w))
forms = sorted(forms - listed)

offs, pos = [], 0
for w in forms: offs.append(pos); pos += len(w) + 1
with open(OUT, 'w') as f:
    f.write('// Generated by Tools/autoswitch/build_forms.py. Do not edit.\n')
    f.write('// English word forms from SCOWL en_US (Hunspell), copyright Kevin Atkinson, permissive license.\n')
    f.write('#ifndef EnglishFormsData_h\n#define EnglishFormsData_h\n\nstatic const char kEnglishFormsWords[] =\n')
    f.write('\n'.join('    "' + ''.join(w + '\\0' for w in forms[i:i + 200]) + '"' for i in range(0, len(forms), 200)) + ';\n')
    f.write(f'static const unsigned int kEnglishFormsOffsets[{len(forms)}] = {{' + ','.join(map(str, offs)) + '};\n')
    f.write(f'static const int kEnglishFormsCount = {len(forms)};\n\n#endif\n')
print(f'{len(forms)} forms ({mode}) -> {os.path.relpath(OUT)}')
